/**
 * Regenerates src/lib/i18n/lug.ts from src/lib/i18n/en.ts with Sunbird AI,
 * the same translator the answers use. Run after changing any UI string:
 *
 *   node --env-file=.env.local node_modules/jiti/lib/jiti-cli.mjs scripts/translate-ui.ts
 *
 * A string whose numbers or {n} placeholder don't survive is kept in English
 * and listed, so nothing silently breaks. The output is machine translation:
 * have a Luganda speaker review it, then edit lug.ts by hand if needed.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { requireEnv } from "../src/lib/env";
import { type MessageKey, en } from "../src/lib/i18n/en";
import { keepsNumbers } from "../src/lib/text/numbers";
import { createSunbird } from "../src/lib/voice/sunbird";

const CONCURRENCY = 6;

async function main() {
  const sunbird = createSunbird({ apiKey: requireEnv("SUNBIRD_API_KEY"), voice: "Namuli" });
  const keys = Object.keys(en) as MessageKey[];
  const out: Partial<Record<MessageKey, string>> = {};
  const kept: MessageKey[] = [];

  let next = 0;
  async function worker() {
    while (next < keys.length) {
      const key = keys[next++] as MessageKey;
      const english = en[key];
      try {
        const lg = (await sunbird.translate(english, "lug", "eng")).trim();
        const placeholdersOk = english.includes("{n}") === lg.includes("{n}");
        if (lg && placeholdersOk && keepsNumbers(english, lg)) {
          out[key] = lg;
        } else {
          kept.push(key);
        }
      } catch (error) {
        if (kept.length === 0) {
          const status = (error as { status?: number }).status;
          console.error(
            `First failure: ${error instanceof Error ? error.message : error} (${status ?? "no status"})`,
          );
        }
        kept.push(key);
      }
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));

  // Failed or unsafe translations are left out, so they show in English.
  const body = keys
    .filter((k) => out[k] !== undefined)
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`)
    .join("\n");
  const file = `import type { Messages } from "./en";

/**
 * Luganda interface strings. GENERATED by scripts/translate-ui.ts with Sunbird
 * AI machine translation, ${new Date().toISOString().slice(0, 10)}. Needs review by a Luganda
 * speaker; hand edits are fine, but re-running the script overwrites them.
 * Keys missing here (failed or unsafe translations) show in English.
 */
export const lug: Partial<Messages> = {
${body}
};
`;
  writeFileSync(resolve("src/lib/i18n/lug.ts"), file);
  console.info(`Wrote ${keys.length} strings, ${kept.length} left in English.`);
  for (const k of kept) console.info(`  left in English: ${k}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
